import type { DocumentRef, HomeComponent, HomeRecord, MediaRef, TimelineEvent } from '../core/types';

/**
 * A worked example of a real home record.
 *
 * This exists so the app can be understood in thirty seconds without anyone having
 * to walk their house with a camera first. Every engine in the app — health,
 * forecast, schedule, transfer — runs against this exactly as it runs against a
 * real record, so what a new user sees here is genuinely what the product does,
 * not a mockup of it.
 *
 * The dates are fixed rather than relative so that the numbers stay reproducible
 * and the tests can assert against them.
 */

const HOME_ID = 'home_sample';

function component(
  input: Omit<HomeComponent, 'homeId' | 'createdAt' | 'updatedAt'>,
): HomeComponent {
  return {
    ...input,
    homeId: HOME_ID,
    createdAt: '2024-01-15T10:00:00.000Z',
    updatedAt: '2026-08-01T10:00:00.000Z',
  };
}

function event(input: Omit<TimelineEvent, 'homeId' | 'createdAt'>): TimelineEvent {
  return { ...input, homeId: HOME_ID, createdAt: `${input.date}T12:00:00.000Z` };
}

